/**
 * Matches a normalized lowercase query against English metadata AND Chinese/Japanese
 * display names, sticker aliases, and category aliases—independent of the active UI locale.
 */
export function matchesStickerSearch(
  item: StickerMeta,
  normalizedQuery: string,
): boolean {
  if (!normalizedQuery) return true;

  if (
    item.name.toLowerCase().includes(normalizedQuery) ||
    item.id.toLowerCase().includes(normalizedQuery) ||
    item.componentName.toLowerCase().includes(normalizedQuery) ||
    item.category.toLowerCase().includes(normalizedQuery) ||
    item.tags.some((tag) => tag.toLowerCase().includes(normalizedQuery))
  ) {
    return true;
  }

  const zhName = zhCNStickerNames[item.id];
  if (zhName?.toLowerCase().includes(normalizedQuery)) {
    return true;
  }

  const jaName = jaStickerNames[item.id];
  if (jaName?.toLowerCase().includes(normalizedQuery)) {
    return true;
  }

  const keywords = STICKER_SEARCH_KEYWORDS[item.id];
  if (keywords?.some((kw) => kw.toLowerCase().includes(normalizedQuery))) {
    return true;
  }

  const categoryAliases = CATEGORY_SEARCH_ALIASES[item.category];
  if (
    categoryAliases?.some((alias) =>
      alias.toLowerCase().includes(normalizedQuery),
    )
  ) {
    return true;
  }

  return false;
}
