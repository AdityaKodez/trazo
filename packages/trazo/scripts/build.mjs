import { execFileSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const pkgDir = path.resolve(__dirname, "..");
const distDir = path.join(pkgDir, "dist");
const tscBin = path.resolve(
  pkgDir,
  "../../node_modules/typescript/bin/tsc",
);

const srcMetaPath = path.join(pkgDir, "src/catalog-meta.ts");

function buildCatalogMetaSource(catalog) {
  const counts = {
    games: 0,
    ocean: 0,
    arrows: 0,
    nature: 0,
    hearts: 0,
    symbols: 0,
    cats: 0,
    characters: 0,
    school: 0,
    food: 0,
  };
  const records = catalog.map((def) => {
    counts[def.category] = (counts[def.category] ?? 0) + 1;
    return {
      id: def.id,
      componentName: def.componentName,
      name: def.name,
      category: def.category,
      mixColor: def.mixColor,
      tags: def.tags,
      viewBox: def.viewBox,
    };
  });

  return [
    `// Auto-generated by packages/trazo/scripts/build.mjs — do not edit by hand.`,
    `import type { StickerCategory, StickerMeta } from "./core";`,
    ``,
    `export type { StickerCategory, StickerMeta } from "./core";`,
    ``,
    `export const trazoCatalogMeta: readonly StickerMeta[] = ${JSON.stringify(records)};`,
    ``,
    `export const STICKER_COUNT = trazoCatalogMeta.length;`,
    ``,
    `export const STICKER_CATEGORY_COUNTS: Readonly<Record<StickerCategory, number>> = ${JSON.stringify(counts)};`,
    ``,
    `const metaById = new Map<string, StickerMeta>(`,
    `  trazoCatalogMeta.map((item) => [item.id, item]),`,
    `);`,
    ``,
    `export function findStickerMeta(id: string): StickerMeta | undefined {`,
    `  return metaById.get(id);`,
    `}`,
    ``,
  ].join("\n");
}

function addJsExtension(specifier) {
  if (!specifier.startsWith("./") && !specifier.startsWith("../")) {
    return specifier;
  }
  if (/\.(?:[cm]?js|json)$/i.test(specifier)) {
    return specifier;
  }
  return `${specifier}.js`;
}

function rewriteRelativeImports(content) {
  return content
    .replace(
      /(\bfrom\s+["'])(\.\.?\/[^"']+)(["'])/g,
      (_, prefix, spec, suffix) => `${prefix}${addJsExtension(spec)}${suffix}`,
    )
    .replace(
      /(\bimport\(\s*["'])(\.\.?\/[^"']+)(["']\s*\))/g,
      (_, prefix, spec, suffix) => `${prefix}${addJsExtension(spec)}${suffix}`,
    );
}

function walk(dir) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const fullPath = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      walk(fullPath);
    } else if (entry.name.endsWith(".js") || entry.name.endsWith(".d.ts")) {
      const source = fs.readFileSync(fullPath, "utf8");
      const updated = rewriteRelativeImports(source);
      if (updated !== source) {
        fs.writeFileSync(fullPath, updated, "utf8");
      }
    }
  }
}

function compileAndRewrite() {
  fs.rmSync(distDir, { recursive: true, force: true });
  execFileSync(process.execPath, [tscBin, "-p", path.join(pkgDir, "tsconfig.json")], {
    stdio: "inherit",
  });
  walk(distDir);
}

compileAndRewrite();

const svg = await import(`${pathToFileURL(path.join(distDir, "svg.js")).href}?t=${Date.now()}`);
const nextMetaSource = buildCatalogMetaSource(svg.trazoCatalog);
const prevMetaSource = fs.existsSync(srcMetaPath) ? fs.readFileSync(srcMetaPath, "utf8") : null;
if (prevMetaSource !== nextMetaSource) {
  fs.writeFileSync(srcMetaPath, nextMetaSource, "utf8");
  compileAndRewrite();
}

const stickers = svg.trazoCatalog.map((def) => {
  const { componentName } = def;
  const definitionName = `${componentName.charAt(0).toLowerCase()}${componentName.slice(1)}Def`;
  if (svg[definitionName] !== def) {
    throw new Error(`Missing SVG export ${definitionName} for ${def.id}`);
  }
  return { componentName, definitionName };
});

fs.writeFileSync(path.join(distDir, "vue.js"), [
  `import { createVueSticker } from "./vue-sticker.js";`,
  `import { ${stickers.map(({ definitionName }) => definitionName).join(", ")} } from "./svg.js";`,
  ...stickers.map(({ componentName, definitionName }) =>
    `export const ${componentName} = /*#__PURE__*/ createVueSticker(${definitionName});`,
  ),
  "",
].join("\n"));

fs.writeFileSync(path.join(distDir, "vue.d.ts"), [
  `import type { createVueSticker } from "./vue-sticker.js";`,
  `type VueSticker = ReturnType<typeof createVueSticker>;`,
  ...stickers.map(({ componentName }) => `export declare const ${componentName}: VueSticker;`),
  "",
].join("\n"));

// Publish Svelte source so the consumer's compiler can target SSR or the browser.
// Each wrapper references the existing definition; no artwork is duplicated.
const svelteDir = path.join(distDir, "svelte");
fs.mkdirSync(svelteDir, { recursive: true });
fs.copyFileSync(
  path.join(pkgDir, "src/svelte/Sticker.svelte"),
  path.join(svelteDir, "Sticker.svelte"),
);
for (const { componentName, definitionName } of stickers) {
  fs.writeFileSync(path.join(svelteDir, `${componentName}.svelte`), [
    `<script lang="ts">`,
    `  import Sticker from "./Sticker.svelte";`,
    `  import { ${definitionName} } from "../svg.js";`,
    `  import type { SvelteStickerProps } from "../svelte-sticker.js";`,
    `  let props: SvelteStickerProps = $props();`,
    `</script>`,
    ``,
    `<Sticker def={${definitionName}} {...props} />`,
    "",
  ].join("\n"));
}

fs.writeFileSync(path.join(distDir, "svelte.js"), [
  ...stickers.map(({ componentName }) =>
    `export { default as ${componentName} } from "./svelte/${componentName}.svelte";`,
  ),
  "",
].join("\n"));

fs.writeFileSync(path.join(distDir, "svelte.d.ts"), [
  `import type { Component } from "svelte";`,
  `import type { SvelteStickerProps } from "./svelte-sticker.js";`,
  `export type { SvelteStickerProps } from "./svelte-sticker.js";`,
  ...stickers.map(({ componentName }) =>
    `export declare const ${componentName}: Component<SvelteStickerProps>;`,
  ),
  "",
].join("\n"));
